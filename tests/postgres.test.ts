import { describe, expect, it } from "vitest";
import { DEFAULT_POSTGRES_OPTIONS, columnFlag, generatePostgres, pgExpression, pgIdentifier, pgType } from "@/app/lib/postgres";
import { makeColumn, makeDemoSchema, makeEmptySchema, makeTable, type Relationship, type Schema } from "@/app/lib/schema";

const relationship = (over: Partial<Relationship> & Pick<Relationship, "startTableId" | "startFieldId" | "endTableId" | "endFieldId">): Relationship => ({
  id: `r_${Math.random()}`, fields: [], name: "", cardinality: "many_to_one", manyLabel: "n", updateConstraint: "No action", deleteConstraint: "No action", ...over,
});

describe("PostgreSQL types", () => {
  it.each([
    ["VARCHAR2", "100", "varchar(100)"], ["VARCHAR2", "50 CHAR", "varchar(50)"], ["NVARCHAR2", "", "text"], ["CHAR", "1", "char(1)"],
    ["NUMBER", "", "numeric"], ["NUMBER", "3", "smallint"], ["NUMBER", "9", "integer"], ["NUMBER", "18", "bigint"], ["NUMBER", "30", "numeric(30)"], ["NUMBER", "10,2", "numeric(10,2)"],
    ["FLOAT", "", "double precision"], ["BINARY_FLOAT", "", "real"], ["DATE", "", "timestamp(0)"], ["TIMESTAMP", "6", "timestamp(6)"],
    ["TIMESTAMP WITH TIME ZONE", "", "timestamptz"], ["CLOB", "", "text"], ["BLOB", "", "bytea"], ["RAW", "16", "uuid"], ["RAW", "32", "bytea"],
  ] as const)("%s(%s) → %s", (type, size, expected) => expect(pgType({ type, size }).type).toBe(expected));
});

describe("expressions", () => {
  it("rewrites Oracle functions, outside string literals only", () => {
    expect(pgExpression("SYSDATE").sql).toBe("localtimestamp(0)");
    expect(pgExpression("TRUNC(SYSDATE)").sql).toBe("current_date");
    expect(pgExpression("NVL(x, 0)").sql).toBe("coalesce(x, 0)");
    expect(pgExpression("'SYSDATE is a word'").sql).toBe("'SYSDATE is a word'");
    expect(pgExpression(`"ORDER" >= 0`).sql).toBe(`"order" >= 0`);
    expect(pgExpression("SYS_GUID()").notes[0]).toMatch(/gen_random_uuid/);
    expect(pgExpression("DECODE(a, 1, 'x')").notes[0]).toMatch(/CASE/);
  });

  it("quotes only the names that need it", () => {
    expect(pgIdentifier("core_grids")).toBe("core_grids");
    expect(pgIdentifier("user")).toBe('"user"');
    expect(pgIdentifier("order")).toBe('"order"');
    expect(pgIdentifier("a#b")).toBe('"a#b"');
  });
});

describe("the script", () => {
  it("writes tables, keys and a foreign key after all tables", () => {
    const { sql, stats, tables } = generatePostgres(makeDemoSchema());
    expect(sql).toContain("create table student (");
    expect(sql).toMatch(/id\s+bigint\s+generated by default as identity/);
    expect(sql.indexOf("alter table enrollment")).toBeGreaterThan(sql.lastIndexOf("create table"));
    expect(sql).toContain("references student (id)");
    // No begin … commit by default: the script runs statement by statement.
    expect(sql).not.toMatch(/^begin;$/m);
    expect(sql).not.toMatch(/^commit;$/m);
    expect(stats).toMatchObject({ tables: 2, foreignKeys: 1 });
    expect(sql.split("\n")[tables[1].line]).toBe("-- enrollment");
  });

  it("gives a foreign-key column the type of the column it points at", () => {
    const { sql, notes } = generatePostgres(makeDemoSchema());
    expect(sql).toMatch(/student_id\s+bigint/);
    expect(notes.some((note) => /takes bigint/.test(note.message))).toBe(true);
  });

  it("follows the options", () => {
    const sql = generatePostgres(makeDemoSchema(), { ...DEFAULT_POSTGRES_OPTIONS, schemaName: "school", dropExisting: true, transaction: false, indexForeignKeys: false }).sql;
    expect(sql).toContain("create schema if not exists school;");
    expect(sql).toContain("drop table if exists student, enrollment cascade;");
    expect(sql).toContain("drop type if exists enrollment_status cascade;");
    expect(sql).not.toMatch(/^begin;$/m);
    expect(sql).not.toContain("_i on enrollment");
  });

  it("writes ON UPDATE and ON DELETE rules", () => {
    const parent = makeTable("PARENT", 0, 0);
    const child = makeTable("CHILD", 0, 0);
    child.columns.push(makeColumn({ name: "PARENT_ID", type: "NUMBER", size: "" }));
    const schema: Schema = { ...makeEmptySchema("x"), tables: [parent, child], relationships: [relationship({ startTableId: child.id, startFieldId: child.columns[1].id, endTableId: parent.id, endFieldId: parent.columns[0].id, deleteConstraint: "Set null", updateConstraint: "Cascade" })] };
    expect(generatePostgres(schema).sql).toContain("on delete set null on update cascade;");
  });

  it("comments out a foreign key into part of a composite key, and says why", () => {
    const parent = makeTable("PARENT", 0, 0);
    parent.keyStrategy = "none";
    parent.columns.push(makeColumn({ name: "B", type: "NUMBER", size: "", pk: true, notNull: true }));
    const child = makeTable("CHILD", 0, 0);
    child.columns.push(makeColumn({ name: "A_ID", type: "NUMBER", size: "" }));
    const schema: Schema = { ...makeEmptySchema("x"), tables: [parent, child], relationships: [relationship({ startTableId: child.id, startFieldId: child.columns[1].id, endTableId: parent.id, endFieldId: parent.columns[0].id })] };
    const { sql, notes, stats } = generatePostgres(schema);
    expect(sql).toMatch(/^-- alter table child$/m);
    expect(stats.foreignKeys).toBe(0);
    expect(notes.find((note) => note.level === "warning")?.message).toMatch(/not its whole primary key/);
  });

  it("shortens names past 63 characters, the same way everywhere", () => {
    const table = makeTable("T", 0, 0);
    table.columns.push(makeColumn({ name: "X".repeat(70), type: "VARCHAR2", size: "1", comment: "c" }));
    const { sql } = generatePostgres({ ...makeEmptySchema("x"), tables: [table] });
    const short = sql.match(/^\s+(x{59}_\w{3})\s/m)?.[1];
    expect(short).toBeTruthy();
    expect(sql).toContain(`comment on column t.${short} is 'c';`);
  });
});

describe("enums", () => {
  const flag = (over: Partial<Parameters<typeof columnFlag>[0]>) => columnFlag({ name: "X", type: "CHAR", check: "", ...over });

  it("reads a CHECK with a list of codes as an enum, Y/N included", () => {
    expect(flag({ name: "STATUS", check: "STATUS IN ('A', 'I', 'P')" })).toEqual({ kind: "enum", values: ["A", "I", "P"] });
    expect(flag({ name: "IS_ACTIVE", check: "IS_ACTIVE IN ('Y', 'N')" })).toEqual({ kind: "enum", values: ["Y", "N"] });
  });

  it("leaves everything else as it is", () => {
    expect(flag({ name: "STATUS", check: "STATUS IN ('A', 'I') OR STATUS IS NULL" })).toBeNull();
    expect(flag({ name: "DELETED", type: "NUMBER", check: "DELETED IN (0, 1)" })).toBeNull();
    expect(flag({ name: "IS_ADMIN" })).toBeNull();
  });

  it("changes only the type: values and defaults stay, and the CHECK the enum replaces goes", () => {
    const table = makeTable("ACCOUNT", 0, 0);
    table.columns.push(
      makeColumn({ name: "IS_ACTIVE", type: "CHAR", size: "1", defaultValue: "'Y'", notNull: true, check: "IS_ACTIVE IN ('Y', 'N')" }),
      makeColumn({ name: "STATUS", type: "VARCHAR2", size: "1", defaultValue: "'A'", check: "STATUS IN ('A', 'B')" }),
      makeColumn({ name: "IS_ADMIN", type: "CHAR", size: "1", defaultValue: "'N'" }),
    );
    const { sql } = generatePostgres({ ...makeEmptySchema("x"), tables: [table] });
    expect(sql).toContain("create type account_is_active as enum ('Y', 'N');");
    expect(sql).toMatch(/is_active\s+account_is_active\s+default 'Y' not null,/);
    expect(sql).toContain("create type account_status as enum ('A', 'B');");
    expect(sql).toMatch(/is_admin\s+char\(1\)\s+default 'N'/);
    expect(sql).not.toContain("check (");
    expect(sql).not.toContain("boolean");
  });
});
